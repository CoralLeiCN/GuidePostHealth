"""Generate frontend wire types from the backend's serialized Pydantic schemas."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from nhs_rag.models import ChatMessage, ChatResponse

OUTPUT = Path(__file__).resolve().parents[1] / "lib" / "api-types.ts"


def typescript(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(typescript(item) for item in schema["anyOf"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{typescript(schema['items'])}>"
    if kind == "object":
        required = schema.get("required", [])
        fields = [
            f"  {name}{'' if name in required else '?'}: {typescript(value)};"
            for name, value in schema["properties"].items()
        ]
        return "{\n" + "\n".join(fields) + "\n}"
    primitives = {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }
    if kind in primitives:
        return primitives[kind]
    raise ValueError(f"Unsupported API schema: {schema}")


def render() -> str:
    definitions: dict[str, Any] = {}
    for model in (ChatMessage, ChatResponse):
        schema = model.model_json_schema(mode="serialization")
        definitions.update(schema.pop("$defs", {}))
        definitions[model.__name__] = schema
    declarations = [
        f"export type {name} = {typescript(schema)};" for name, schema in definitions.items()
    ]
    return (
        "// Generated by npm run types:generate. Do not edit by hand.\n\n"
        + "\n\n".join(declarations)
        + "\n"
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != generated:
            parser.exit(1, "API types are stale. Run npm run types:generate.\n")
    else:
        OUTPUT.write_text(generated, encoding="utf-8")
